CREATE DATABASE IF NOT EXISTS cv CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'cv'@'%' IDENTIFIED BY 'cv';
GRANT ALL PRIVILEGES ON cv.* TO 'cv'@'%';
USE cv;

CREATE TABLE IF NOT EXISTS `user` (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS experiences (
    id INT AUTO_INCREMENT PRIMARY KEY,
    poste VARCHAR(255) NOT NULL,
    entreprise VARCHAR(255) NOT NULL,
    debut DATE NOT NULL,
    fin DATE NULL,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS diplomes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    intitule VARCHAR(255) NOT NULL,
    etablissement VARCHAR(255) NOT NULL,
    annee SMALLINT NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS langues (
    id INT AUTO_INCREMENT PRIMARY KEY,
    langue VARCHAR(100) NOT NULL,
    niveau VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS permis (
    id INT AUTO_INCREMENT PRIMARY KEY,
    type VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS interets (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    icone VARCHAR(100) NOT NULL,
    description TEXT NULL
);

CREATE TABLE IF NOT EXISTS languages (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    icone VARCHAR(100) NOT NULL,
    niveau VARCHAR(50) NOT NULL
);
